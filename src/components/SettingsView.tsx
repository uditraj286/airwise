"use client";

import { PageHeader } from "@/components/ui/PageHeader";
import { AlertsSettings } from "@/components/AlertsSettings";
import { useState } from "react";
import { LocationPicker } from "@/components/LocationPicker";
import { ThemeToggle } from "@/components/layout/ThemeToggle";
import { Card } from "@/components/ui/Card";
import { Segmented } from "@/components/ui/Segmented";
import { CloudPanel } from "@/components/CloudPanel";
import { deleteCloudData, useCloudStatus } from "@/lib/firebase/sync";
import { clearAllLocalData, useProfile } from "@/lib/profile/store";
import type { Language } from "@/lib/types";

/** Language, theme, privacy and data reset. */
export function SettingsView() {
  const { profile, isDemo, save } = useProfile();
  const [cleared, setCleared] = useState(false);
  const cloud = useCloudStatus();

  return (
    <div className="mx-auto max-w-3xl space-y-6">
      <PageHeader title="Settings" subtitle="Language, look, alerts, location and your data." />
      <AlertsSettings />
      <Card>
        <h2 className="text-lg font-medium">Language</h2>
        <p className="mt-1 text-sm text-muted">Used for the interface, your AI plan and chat answers.</p>
        <div className="mt-4">
          <Segmented<Language>
            label="Language"
            value={profile.language}
            onChange={(language) =>
              save({ ...profile, language, locationConfirmed: isDemo ? false : profile.locationConfirmed })
            }
            options={[
              { value: "en", label: "English" },
              { value: "hi", label: "हिन्दी" },
            ]}
          />
        </div>
        {isDemo && (
          <p className="mt-3 text-xs text-muted">
            Changing language saves the demo household to this device.
          </p>
        )}
      </Card>

      <Card>
        <h2 className="text-lg font-medium">Appearance</h2>
        <div className="mt-4">
          <ThemeToggle />
        </div>
      </Card>

      <CloudPanel />

      <Card>
        <h2 className="text-lg font-medium">Air quality location</h2>
        <p className="mt-1 text-sm text-muted">
          Choose where AirWise gets air quality and forecasts for your household.
        </p>
        <div className="mt-4">
          <LocationPicker
            value={isDemo || profile.locationConfirmed === false ? undefined : profile.location}
            onChange={(location) => save({ ...profile, location, locationConfirmed: true })}
          />
          {cloud.state === "ready" &&
            !cloud.isAnonymous &&
            !isDemo &&
            profile.locationConfirmed !== false && (
              <button
                type="button"
                className="mt-3 text-sm text-muted underline underline-offset-4"
                onClick={() => save({ ...profile, locationConfirmed: false })}
              >
                Clear saved location
              </button>
            )}
        </div>
      </Card>

      <Card>
        <h2 className="text-lg font-medium">Privacy</h2>
        <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-muted">
          <li>Your household profile and progress are stored in this browser.</li>
          <li>
            With cloud sync on, it is also saved in Firebase under an anonymous ID that only you can read
            (enforced by Firestore security rules).
          </li>
          <li>Community pledges store only your city and which swaps you chose — no names.</li>
          <li>Location is rounded to about 1 km before air data is looked up or cached.</li>
          <li>
            Plans are generated by Google Gemini from household details (first names, age groups, conditions)
            without any identifiers.
          </li>
        </ul>
        <button
          type="button"
          onClick={async () => {
            try {
              await deleteCloudData();
            } catch {
              /* offline: local data is still cleared */
            }
            clearAllLocalData();
            setCleared(true);
          }}
          className="mt-4 rounded-full border border-bad/40 px-4 py-2 text-sm text-bad hover:bg-bad/5"
        >
          Delete all my data (device + cloud)
        </button>
        <p role="status" className="mt-2 text-sm text-good">
          {cleared ? "All AirWise data removed." : ""}
        </p>
      </Card>
    </div>
  );
}
